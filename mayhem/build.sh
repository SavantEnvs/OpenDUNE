#!/usr/bin/env bash
#
# mayhem/build.sh — build OpenDUNE's fuzz harnesses and the functional oracle.
#
# OpenDUNE ships a hand-written ./configure that generates Makefiles in the tree root (and needs a
# video backend: SDL/SDL2/...). We instead compile the same headless source set that
# `./configure --without-sdl --without-sdl2 --without-asound --without-pulse` selects from
# source.list (dsp_none, midi_none, crashlog_none, os/error, os/readdir) into an out-of-tree,
# gitignored build dir, plus mayhem/harnesses/video_stub.c (upstream has no "none" video driver).
# opendune.c is compiled with -Dmain=opendune_main so its globals and Game_* helpers link but
# its interactive main() does not.
set -euo pipefail
[ -n "${SOURCE_DATE_EPOCH:-}" ] || unset SOURCE_DATE_EPOCH

: "${SANITIZER_FLAGS=-fsanitize=address,undefined -fno-sanitize-recover=all -fno-omit-frame-pointer}"
: "${DEBUG_FLAGS:=-g -gdwarf-3}"
: "${CC:=clang}" ; : "${CXX:=clang++}" ; : "${LIB_FUZZING_ENGINE:=-fsanitize=fuzzer}"
: "${MAYHEM_JOBS:=$(nproc)}"
: "${COVERAGE_FLAGS=}"
: "${SRC:=/mayhem}"
export SANITIZER_FLAGS DEBUG_FLAGS CC CXX LIB_FUZZING_ENGINE MAYHEM_JOBS COVERAGE_FLAGS

cd "$SRC"
B="$SRC/mayhem/build"          # gitignored by mayhem/.gitignore
OUT="$SRC/mayhem/out"          # fuzz + standalone + test binaries (gitignored)
mkdir -p "$B" "$OUT"

ENGINE_SRCS="animation.c audio/driver.c audio/dsp_none.c audio/midi_none.c audio/mt32mpu.c
audio/sound.c codec/format40.c codec/format80.c config.c crashlog/crashlog.c crashlog/crashlog_none.c
cutscene.c explosion.c file.c gfx.c gui/editbox.c gui/font.c gui/gui.c gui/mentat.c gui/security.c
gui/viewport.c gui/widget.c gui/widget_click.c gui/widget_draw.c house.c ini.c inifile.c
input/input.c input/mouse.c load.c map.c object.c opendune.c os/endian.c os/error.c os/readdir.c
pool/house.c pool/structure.c pool/team.c pool/unit.c save.c saveload/house.c saveload/info.c
saveload/map.c saveload/object.c saveload/saveload.c saveload/scenario.c saveload/scriptengine.c
saveload/structure.c saveload/team.c saveload/unit.c scenario.c script/general.c script/script.c
script/structure.c script/team.c script/unit.c sprites.c string.c structure.c table/actioninfo.c
table/animation.c table/explosion.c table/houseanimation.c table/houseinfo.c table/landscapeinfo.c
table/movementtype.c table/selectiontype.c table/sound.c table/structureinfo.c table/teamaction.c
table/tilediff.c table/unitinfo.c table/widget.c table/widgetinfo.c table/windowdesc.c team.c tile.c
timer.c tools.c unit.c video/video_fps.c video/hqx_init.c video/hq2x_8b.c video/hq3x_8b.c
video/hq4x_8b.c video/scalebit.c video/scale2x.c video/scale3x.c wsa.c"

# rev.c is generated by upstream's Makefile from rev.c.in; generate it into the build dir.
sed -e 's/!!VERSION!!/mayhem/' -e 's/!!MODIFIED!!/0/' src/rev.c.in > "$B/rev.c.new"
cmp -s "$B/rev.c.new" "$B/rev.c" 2>/dev/null || mv "$B/rev.c.new" "$B/rev.c"; rm -f "$B/rev.c.new"

DEFS="-DUNIX -DLINUX -Dmain=opendune_main -I$SRC/include -iquote $SRC/src -w"

# build_lib <dir> <cflags...>: compile the engine into <dir>/libopendune.a
build_lib() {
  local dir="$1"; shift
  local flags="$*"
  mkdir -p "$dir"
  local objs=() s in o
  for s in $ENGINE_SRCS rev.c video_stub.c; do
    in="$SRC/src/$s"
    [ "$s" = rev.c ] && in="$B/rev.c"
    [ "$s" = video_stub.c ] && in="$SRC/mayhem/harnesses/video_stub.c"
    o="$dir/$(echo "$s" | tr / _).o"
    objs+=("$o")
    printf '%s %s\n' "$in" "$o"
  done > "$dir/objs.list"
  xargs -P"$MAYHEM_JOBS" -n2 sh -c '$CC '"$flags"' '"$DEFS"' -c "$0" -o "$1"' < "$dir/objs.list"
  rm -f "$dir/libopendune.a"
  ar rcs "$dir/libopendune.a" "${objs[@]}"
}

# 1) the engine, instrumented (ASan+UBSan, halting) with DWARF 3 + SanCov for libFuzzer
build_lib "$B/fuzz" $SANITIZER_FLAGS $DEBUG_FLAGS -fsanitize=fuzzer-no-link -O1
$CC $SANITIZER_FLAGS $DEBUG_FLAGS -c "$SRC/mayhem/lsan_off.c" -o "$B/lsan_off.o"
$CC $SANITIZER_FLAGS $DEBUG_FLAGS -c "$STANDALONE_FUZZ_MAIN" -o "$B/standalone_main.o"

# 2) the libFuzzer harnesses, each linked twice (libFuzzer + run-once standalone reproducer).
#    The AFL_TARGETS are built in step 2b instead.
AFL_TARGETS="fuzz_sprites fuzz_cps fuzz_font fuzz_strings fuzz_wsa"
for h in "$SRC"/mayhem/harnesses/fuzz_*.c; do
  n=$(basename "$h" .c)
  case " $AFL_TARGETS " in *" $n "*) continue ;; esac
  $CC $SANITIZER_FLAGS $DEBUG_FLAGS -fsanitize=fuzzer-no-link $DEFS -c "$h" -o "$B/$n.o"
  $CC $SANITIZER_FLAGS $DEBUG_FLAGS $LIB_FUZZING_ENGINE "$B/$n.o" "$B/fuzz/libopendune.a" \
      "$B/lsan_off.o" -lm -lpthread -o "$OUT/$n"
  $CC $SANITIZER_FLAGS $DEBUG_FLAGS "$B/standalone_main.o" "$B/$n.o" "$B/fuzz/libopendune.a" \
      "$B/lsan_off.o" -lm -lpthread -o "$OUT/$n-standalone"
done

# 2b) AFL targets (forkserver, one input per process; each is its own reproducer): the engine and
#     harness compiled with afl-clang-fast and the same sanitizers, main() from afl_main.c.
#     (fuzz_xmi is libFuzzer: as an AFL target Mayhem recorded 0 edges for it.)
#     fuzz_sprites: Sprites_Uninit() does not reset the static sprite count, so a second load in
#     one process would free stale pointers. The others fault on almost every short input (the
#     engine reads fixed header fields of its data files without length checks), which stops a
#     libFuzzer process at its first input.
CC="afl-clang-fast" build_lib "$B/afl" $SANITIZER_FLAGS $DEBUG_FLAGS -O1
afl-clang-fast $SANITIZER_FLAGS $DEBUG_FLAGS -c "$SRC/mayhem/harnesses/afl_main.c" -o "$B/afl_main.o"
for n in $AFL_TARGETS; do
  afl-clang-fast $SANITIZER_FLAGS $DEBUG_FLAGS $DEFS -DLLVMFuzzerTestOneInput=fz_one_input \
      -c "$SRC/mayhem/harnesses/$n.c" -o "$B/$n.afl.o"
  afl-clang-fast $SANITIZER_FLAGS $DEBUG_FLAGS "$B/afl_main.o" "$B/$n.afl.o" \
      "$B/afl/libopendune.a" "$B/lsan_off.o" -lm -lpthread -o "$OUT/$n"
  rm -f "$OUT/$n-standalone"
done

# 3) the functional oracle: the engine with NORMAL flags (no sanitizers) + mayhem/tests/selftest.c,
#    which loads hand-built game files through the engine's loaders and asserts the decoded values.
build_lib "$B/test" -O2 $COVERAGE_FLAGS
$CC -O2 $COVERAGE_FLAGS ${DEFS/-Dmain=opendune_main/} "$SRC/mayhem/tests/selftest.c" "$B/test/libopendune.a" -lm -lpthread \
    $COVERAGE_FLAGS -o "$OUT/opendune_selftest"
$CC -O2 $COVERAGE_FLAGS -I"$SRC/include" "$SRC/src/tools/extractpak.c" -o "$OUT/extractpak_plain"
echo "build OK"
